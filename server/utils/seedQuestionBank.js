async function seedQuestionBank() {
  try {
    const count = await QuestionBank.countDocuments();
    if (count < 20) {
      await QuestionBank.deleteMany({});
      await QuestionBank.insertMany(SEED_QUESTIONS);
      console.log(`✅ Seeded ${SEED_QUESTIONS.length} questions into QuestionBank.`);
    }
  } catch (err) {
    console.error("Error seeding QuestionBank:", err.message);
  }
}

